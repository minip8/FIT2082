"""Write the run lists for the frozen comparison on MONSTER's five test folds.

Both models were tuned the same way on fold 0's validation and tune slices
(README `m3`): HashBoost chooses between `G` and `L`, XGBoost between
`d4_lr0.1` and `d8_bin64`, per dataset on tune error. Those choices are frozen
here from fold 0, so each fold trains one configuration per model: HashBoost's
is the majority over its five seeds (all five agreed except WhaleSounds, 4 of
5), XGBoost's its one run's. Nothing below was chosen on a test fold.

Each run trains on fold k's pool with `--fold k`, draws validation and tune
from it as fold 0 does, stops on tune, and scores the tune-chosen model once on
the fold's test rows (`--test`). One run per fold, model seed 42.

Two jobs per fold, balanced by fold 0's training times (about 16,000 s each):
S2Agri-10pc-34, whose XGBoost run alone took 12,887 s, with three mid-sized
datasets, and everything else.

    uv run python scripts/m3_runs/test_runs.py   # rewrites test_*.txt
"""

from pathlib import Path

from configs import COMMON as HB_COMMON
from configs import CONFIGS as HB_CONFIGS
from monster_benchmark import split_flags
from xgb_screen import COMMON as XGB_COMMON
from xgb_screen2 import ARMS as XGB_ARMS

FOLDS = range(5)

# dataset: (HashBoost config, XGBoost arm), frozen from fold 0
PICKS = {
    "AudioMNIST-DS": ("G", "d4_lr0.1"),
    "CornellWhaleChallenge": ("G", "d8_bin64"),
    "CrowdSourced": ("G", "d4_lr0.1"),
    "DREAMERA": ("L", "d8_bin64"),
    "DREAMERV": ("L", "d8_bin64"),
    "FordChallenge": ("G", "d8_bin64"),
    "FruitFlies": ("G", "d4_lr0.1"),
    "InsectSound": ("G", "d4_lr0.1"),
    "LakeIce": ("G", "d4_lr0.1"),
    "LenDB": ("L", "d4_lr0.1"),
    "MosquitoSound": ("G", "d4_lr0.1"),
    "Opportunity": ("G", "d4_lr0.1"),
    "PAMAP2": ("G", "d4_lr0.1"),
    "Pedestrian": ("L", "d8_bin64"),
    "S2Agri-10pc-17": ("L", "d8_bin64"),
    "S2Agri-10pc-34": ("L", "d8_bin64"),
    "STEW": ("G", "d4_lr0.1"),
    "Skoda": ("G", "d4_lr0.1"),
    "TimeSen2Crop": ("G", "d4_lr0.1"),
    "Tiselac": ("G", "d4_lr0.1"),
    "Traffic": ("L", "d8_bin64"),
    "UCIActivity": ("G", "d4_lr0.1"),
    "USCActivity": ("G", "d4_lr0.1"),
    "WISDM": ("G", "d4_lr0.1"),
    "WISDM2": ("G", "d4_lr0.1"),
    "WhaleSounds": ("L", "d8_bin64"),
}

HEAVY = ["S2Agri-10pc-34", "MosquitoSound", "WhaleSounds", "Pedestrian"]
REST = [name for name in PICKS if name not in HEAVY]


def lines(name: str, fold: int) -> list[str]:

    hb, xgb = PICKS[name]
    common = (
        f'python scripts/stream_full.py --path "$DATA" --dataset {name}'
        f"{split_flags(name)} --fold {fold} --test --out results/test/fold{fold}"
    )

    return [
        f"{common} {HB_COMMON} {HB_CONFIGS[hb]} --label hb_{hb}",
        f"{common} {XGB_COMMON} {XGB_ARMS[xgb]} --label xgb_{xgb}",
    ]


def main() -> None:

    here = Path(__file__).parent

    for fold in FOLDS:
        for part, names in (("a", HEAVY), ("b", REST)):
            job = f"test_f{fold}{part}"
            header = [
                f"# Generated by test_runs.py: fold {fold}, {', '.join(names)}.",
                "#",
                f"#     sbatch -c 8 --mem=128G --time=1-00:00:00 -J {job.replace('_', '-')} \\",
                f"#         scripts/m3_job.sh --stage {','.join(names)} \\",
                f"#         --serial scripts/m3_runs/{job}.txt",
                "",
            ]
            body = [line for name in names for line in lines(name, fold)]
            (here / f"{job}.txt").write_text("\n".join(header + body) + "\n")
            print(f"{job}: {len(names)} datasets, {len(body)} runs")


if __name__ == "__main__":
    main()
