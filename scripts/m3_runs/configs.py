"""Write the run lists for three HashBoost configurations on all of MONSTER.

The lever screen (`levers.py`, `levers2.py`, README `m3`) found that what
helps depends on the pool. Gain-scored splits with heavy leaf L2 and 6-bit
tables cut small-pool error up to tenfold and pass XGBoost on several, but
overfit Traffic and DREAMERA. Leaf L2 at 16 rounds per batch is best on Traffic
and LenDB. So three configurations, fixed from the screen before running on
the other 15 datasets, on the benchmark's splits and datasets
(`monster_benchmark.py`):

* `G` (gain): GainSplitter with 64 candidates, leaf L2 100, 6 bits; 8 rounds
  per batch, 128-batch window, the benchmark's budget.
* `L` (large): leaf L2 1, 16 rounds per batch, 128-batch window, the same
  budget.
* `F` (fast): GainSplitter with 16 candidates, leaf L2 100, 6 bits, and a
  short budget: at most 2,000 batches, stopping 250 batches after the best tune
  evaluation.

All three use the feature cache, so a pool whose features fit trains without
recomputing QUANT. Choosing between `G` and `L` per dataset on the tune slice
needs no further runs, so the README quotes that as well.

    uv run python scripts/m3_runs/configs.py   # rewrites configs_*.txt
"""

from pathlib import Path

from monster_benchmark import JOBS as BENCHMARK_JOBS
from monster_benchmark import split_flags

COMMON = (
    "--model hashboost --compile --epochs 100000 --eval-every 50 --feature-cache-gb 20"
)

CONFIGS = {
    "G": "--max-batches 5000 --patience-batches 1000 --hashes-per-round 8 "
    "--active-batches 128 --gain-candidates 64 --hessian-eps 100 --num-bits 6",
    "L": "--max-batches 5000 --patience-batches 1000 --hashes-per-round 16 "
    "--active-batches 128 --hessian-eps 1",
    "F": "--max-batches 2000 --patience-batches 250 --hashes-per-round 8 "
    "--active-batches 128 --gain-candidates 16 --hessian-eps 100 --num-bits 6",
}

JOBS = {
    job.replace("monster", "configs"): names for job, names in BENCHMARK_JOBS.items()
}


def lines(name: str) -> list[str]:

    common = (
        f'python scripts/stream_full.py --path "$DATA" --dataset {name}'
        f"{split_flags(name)} --out results/configs {COMMON}"
    )

    return [f"{common} {flags} --label {label}" for label, flags in CONFIGS.items()]


def main() -> None:

    here = Path(__file__).parent

    for job, names in JOBS.items():
        header = [
            f"# Generated by configs.py: {', '.join(names)}.",
            "#",
            f"#     sbatch -c 8 --mem=96G --time=08:00:00 -J {job.replace('_', '-')} \\",
            f"#         scripts/m3_job.sh --stage {','.join(names)} \\",
            f"#         --serial scripts/m3_runs/{job}.txt",
            "",
        ]
        body = [line for name in names for line in lines(name)]
        (here / f"{job}.txt").write_text("\n".join(header + body) + "\n")
        print(f"{job}: {len(names)} datasets, {len(body)} runs")


if __name__ == "__main__":
    main()
