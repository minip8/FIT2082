"""Write the run lists for QUANT's ExtraTrees on MONSTER's five test folds.

ExtraTrees is the classifier QUANT ships with, and on UCR it beat both
boosters (README `ucr`), so it joins the frozen comparison (`test_runs.py`) as
a third model. It fits at QUANT's fixed settings and chooses nothing, so each
fold trains it once on the boosters' training rows and scores it on the same
test rows.

sklearn has no GPU path, so these are CPU jobs (`comp`, 36-48 cores and about
373 GB a node). Each job holds one pool's features in RAM at a time:
TimeSen2Crop's are 100 GB, LenDB's 58 GB and S2Agri's 32 GB. The forest adds
a few GB, and S2Agri's 29 classes could push its forest towards 50 GB. Fit
time grows with n log n times the number of features, measured locally at
2.6e-9 s per unit on 12 threads (WISDM, Tiselac, InsectSound). Two jobs per
fold, balanced on that estimate at about 4 h each on 36 cores:
TimeSen2Crop, MosquitoSound and both DREAMERs, then everything else.

    uv run python scripts/m3_runs/et_runs.py   # rewrites et_*.txt
"""

from pathlib import Path

from monster_benchmark import split_flags
from test_runs import FOLDS, PICKS

HEAVY = ["TimeSen2Crop", "MosquitoSound", "DREAMERA", "DREAMERV"]
REST = [name for name in PICKS if name not in HEAVY]


def line(name: str, fold: int) -> str:

    return (
        f'python scripts/stream_full.py --path "$DATA" --dataset {name}'
        f"{split_flags(name)} --fold {fold} --test --out results/test/fold{fold}"
        " --model extratrees --device cpu --label et"
    )


def main() -> None:

    here = Path(__file__).parent

    for fold in FOLDS:
        for part, names in (("a", HEAVY), ("b", REST)):
            job = f"et_f{fold}{part}"
            header = [
                f"# Generated by et_runs.py: fold {fold}, {', '.join(names)}.",
                "#",
                "#     sbatch -p comp --gres=none -c 36 --mem=200G --time=16:00:00 \\",
                f"#         -J {job.replace('_', '-')} scripts/m3_job.sh \\",
                f"#         --serial scripts/m3_runs/{job}.txt",
                "",
            ]
            body = [line(name, fold) for name in names]
            (here / f"{job}.txt").write_text("\n".join(header + body) + "\n")
            print(f"{job}: {len(body)} runs")


if __name__ == "__main__":
    main()
