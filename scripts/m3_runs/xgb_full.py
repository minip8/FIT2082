"""Write the run lists for round 3 of the XGBoost screen: the chosen pair on
the rest of MONSTER.

Rounds 1 and 2 (`xgb_screen.py`, `xgb_screen2.py`, README `m3`) fixed two
XGBoost settings on HashBoost's 10 screen datasets, as HashBoost's `G` and `L`
were fixed, with the 5,000-round cap and 100 rounds of patience:

* `d4_lr0.1`: depth 4, learning rate 0.1 (small pools)
* `d8_bin64`: depth 8 on 64 histogram bins (large pools; 64 bins fit wide
  feature sets that depth 8 at 256 does not)

`auto(d4_lr0.1,d8_bin64)` picks between them on tune error, mirroring
`auto(G,L)`. The screened 10 already have both, so this runs the other 16,
on the benchmark's splits. Jobs are sized by the default run's time: the two
S2Agri subsets took 2,811 and 4,870 s for 1,000 rounds at depth 6 and could
take several times that now, so each gets a job of its own.

    uv run python scripts/m3_runs/xgb_full.py   # rewrites xgb_full_*.txt
"""

from pathlib import Path

from monster_benchmark import split_flags
from xgb_screen import COMMON
from xgb_screen2 import ARMS as SCREEN2_ARMS

ARMS = {label: SCREEN2_ARMS[label] for label in ("d4_lr0.1", "d8_bin64")}

# job: (datasets, sbatch --time)
JOBS = {
    "xgb_full_a": (["TimeSen2Crop", "DREAMERV"], "1-00:00:00"),
    "xgb_full_b": (
        ["MosquitoSound", "WhaleSounds", "Pedestrian", "LakeIce", "WISDM2"],
        "12:00:00",
    ),
    "xgb_full_c": (["S2Agri-10pc-17"], "2-00:00:00"),
    "xgb_full_d": (["S2Agri-10pc-34"], "2-00:00:00"),
    "xgb_full_e": (
        [
            "AudioMNIST-DS",
            "CornellWhaleChallenge",
            "FruitFlies",
            "Opportunity",
            "Skoda",
            "Tiselac",
            "USCActivity",
        ],
        "12:00:00",
    ),
}


def lines(name: str) -> list[str]:

    common = (
        f'python scripts/stream_full.py --path "$DATA" --dataset {name}'
        f"{split_flags(name)} --out results/xgb-full {COMMON}"
    )

    return [f"{common} {flags} --label xgb_{label}" for label, flags in ARMS.items()]


def main() -> None:

    here = Path(__file__).parent

    for job, (names, time) in JOBS.items():
        header = [
            f"# Generated by xgb_full.py: {', '.join(names)}.",
            "#",
            f"#     sbatch -c 8 --mem=96G --time={time} -J {job.replace('_', '-')} \\",
            f"#         scripts/m3_job.sh --stage {','.join(names)} \\",
            f"#         --serial scripts/m3_runs/{job}.txt",
            "",
        ]
        body = [line for name in names for line in lines(name)]
        (here / f"{job}.txt").write_text("\n".join(header + body) + "\n")
        print(f"{job}: {len(names)} datasets, {len(body)} runs")


if __name__ == "__main__":
    main()
