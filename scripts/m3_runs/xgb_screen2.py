"""Write the run lists for round 2 of the XGBoost screen on M3.

Round 1 (`xgb_screen.py`, README `m3`) found that the 5,000-round cap alone
takes XGBoost to 0.924x its default error, and that depth splits the pools as
`G` and `L` do for HashBoost: depth 4 is best on the small activity pools,
8 or 10 on Traffic, LenDB and FordChallenge. Depth 8 and 10 ran out of the
L40S on wide feature sets, and subsampling helped a little. This round builds
a small-pool and a large-pool candidate on the same 10 datasets, cap and
patience:

* `d4_sub`, `d4_lr0.1`: depth 4 with subsampling, or faster
* `base_bin64`: 64 histogram bins alone, what fewer bins cost
* `d8_bin64`, `d10_bin64`: deep trees on 64 bins, a quarter of the histogram
  memory, so they may fit the wide sets
* `d10_sub_bin64`: the large-pool candidate with subsampling

    uv run python scripts/m3_runs/xgb_screen2.py   # rewrites xgb_screen2_*.txt
"""

from pathlib import Path

from monster_benchmark import split_flags
from xgb_screen import COMMON
from xgb_screen import JOBS as SCREEN_JOBS

SUB = "--subsample 0.8 --colsample-bynode 0.5"

ARMS = {
    "d4_sub": f"--max-depth 4 {SUB}",
    "d4_lr0.1": "--max-depth 4 --learning-rate 0.1",
    "base_bin64": "--max-bin 64",
    "d8_bin64": "--max-depth 8 --max-bin 64",
    "d10_bin64": "--max-depth 10 --max-bin 64",
    "d10_sub_bin64": f"--max-depth 10 --max-bin 64 {SUB}",
}

JOBS = {job.replace("screen", "screen2"): names for job, names in SCREEN_JOBS.items()}


def lines(name: str) -> list[str]:

    common = (
        f'python scripts/stream_full.py --path "$DATA" --dataset {name}'
        f"{split_flags(name)} --out results/xgb-screen2 {COMMON}"
    )

    return [f"{common} {flags} --label xgb_{label}" for label, flags in ARMS.items()]


def main() -> None:

    here = Path(__file__).parent

    for job, names in JOBS.items():
        header = [
            f"# Generated by xgb_screen2.py: {', '.join(names)}.",
            "#",
            f"#     sbatch -c 8 --mem=96G --time=08:00:00 -J {job.replace('_', '-')} \\",
            f"#         scripts/m3_job.sh --stage {','.join(names)} \\",
            f"#         --serial scripts/m3_runs/{job}.txt",
            "",
        ]
        body = [line for name in names for line in lines(name)]
        (here / f"{job}.txt").write_text("\n".join(header + body) + "\n")
        print(f"{job}: {len(names)} datasets, {len(body)} runs")


if __name__ == "__main__":
    main()
