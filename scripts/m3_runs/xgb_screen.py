"""Write the run lists for round 1 of an XGBoost screen on M3.

HashBoost's configurations came from two lever screens on 10 datasets
(`levers.py`, `levers2.py`) and a tune-slice choice between two of them
(`configs.py`, README `m3`), while XGBoost ran once at its defaults (depth 6,
learning rate 0.05, a 1,000-round cap). To compare them fairly XGBoost gets the
same procedure, starting here on the same 10 datasets and splits. Its default
runs (`monster_benchmark.py`) reach training error 0 on the small pools, end
underfitted on the large ones (Traffic 0.29, LenDB 0.035) and stop within 100
rounds of the cap on Traffic, DREAMERV and MosquitoSound. So every arm raises
the cap to 5,000 rounds with 100 of patience, and each changes one thing:

* `base`: the cap alone
* `d4`, `d8`, `d10`: tree depth
* `lr0.1`: learning rate 0.1
* `sub`: rows subsampled at 0.8 per tree and columns at 0.5 per split
* `l2`: `reg_lambda` 10 and `min_child_weight` 5

    uv run python scripts/m3_runs/xgb_screen.py   # rewrites xgb_screen_*.txt
"""

from pathlib import Path

from monster_benchmark import split_flags

COMMON = (
    "--model xgboost --in-memory --num-boost-round 5000 --early-stopping-rounds 100"
)

ARMS = {
    "base": "",
    "d4": "--max-depth 4",
    "d8": "--max-depth 8",
    "d10": "--max-depth 10",
    "lr0.1": "--learning-rate 0.1",
    "sub": "--subsample 0.8 --colsample-bynode 0.5",
    "l2": "--reg-lambda 10 --min-child-weight 5",
}

# balanced by the default run's time (README `m3`): about 600, 400 and 400 s
JOBS = {
    "xgb_screen_a": ["PAMAP2", "InsectSound", "WISDM", "UCIActivity"],
    "xgb_screen_b": ["DREAMERA", "CrowdSourced", "FordChallenge"],
    "xgb_screen_c": ["Traffic", "LenDB", "STEW"],
}


def lines(name: str) -> list[str]:

    common = (
        f'python scripts/stream_full.py --path "$DATA" --dataset {name}'
        f"{split_flags(name)} --out results/xgb-screen {COMMON}"
    )

    return [
        f"{common} {flags} --label xgb_{label}".replace("  ", " ")
        for label, flags in ARMS.items()
    ]


def main() -> None:

    here = Path(__file__).parent

    for job, names in JOBS.items():
        header = [
            f"# Generated by xgb_screen.py: {', '.join(names)}.",
            "#",
            f"#     sbatch -c 8 --mem=96G --time=08:00:00 -J {job.replace('_', '-')} \\",
            f"#         scripts/m3_job.sh --stage {','.join(names)} \\",
            f"#         --serial scripts/m3_runs/{job}.txt",
            "",
        ]
        body = [line for name in names for line in lines(name)]
        (here / f"{job}.txt").write_text("\n".join(header + body) + "\n")
        print(f"{job}: {len(names)} datasets, {len(body)} runs")


if __name__ == "__main__":
    main()
