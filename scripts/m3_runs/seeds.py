"""Write the run lists for four more seeds of `G` and `L` on M3.

The configurations (`configs.py`, README `m3`) were each run once, and a rerun
moves validation error by about 0.005 on small pools and 0.008 on Traffic and
LenDB, as large as many of the gaps to XGBoost. This reruns `G` and `L`, which
are also what `auto(G,L)` chooses between, with model seeds 1-4 on the same
splits: `--seed 42` still draws the rows, `--model-seed` only the hashes and
the batch order. With the original runs (model seed 42) that is five per
configuration. Each job goes seed by seed, so a job cut short leaves whole
seeds.

    uv run python scripts/m3_runs/seeds.py   # rewrites seeds_*.txt
"""

from pathlib import Path

from configs import COMMON
from configs import CONFIGS as CONFIG_FLAGS
from configs import JOBS as CONFIG_JOBS
from monster_benchmark import split_flags

SEEDS = [1, 2, 3, 4]
CONFIGS = {label: CONFIG_FLAGS[label] for label in ("G", "L")}

JOBS = {job.replace("configs", "seeds"): names for job, names in CONFIG_JOBS.items()}


def lines(name: str, seed: int) -> list[str]:

    common = (
        f'python scripts/stream_full.py --path "$DATA" --dataset {name}'
        f"{split_flags(name)} --out results/seeds {COMMON} --model-seed {seed}"
    )

    return [
        f"{common} {flags} --label {label}_s{seed}" for label, flags in CONFIGS.items()
    ]


def main() -> None:

    here = Path(__file__).parent

    for job, names in JOBS.items():
        header = [
            f"# Generated by seeds.py: {', '.join(names)}.",
            "#",
            f"#     sbatch -c 8 --mem=96G --time=08:00:00 -J {job.replace('_', '-')} \\",
            f"#         scripts/m3_job.sh --stage {','.join(names)} \\",
            f"#         --serial scripts/m3_runs/{job}.txt",
            "",
        ]
        body = [line for seed in SEEDS for name in names for line in lines(name, seed)]
        (here / f"{job}.txt").write_text("\n".join(header + body) + "\n")
        print(f"{job}: {len(names)} datasets, {len(body)} runs")


if __name__ == "__main__":
    main()
