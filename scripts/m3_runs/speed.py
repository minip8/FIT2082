"""Write the run lists for the HashBoost speed round on M3.

Three configurations over all of MONSTER (`configs.py`, README `m3`) left a
speed question. `F` (16 candidates, a 2,000-batch budget with 250 batches of
patience) trains in a third of `G`'s time and is within 0.006 of it on 19
datasets, but 0.016-0.038 behind on InsectSound, MosquitoSound, Traffic and the
S2Agri subsets. This separates its two savings and tries a cheap large-pool
configuration, on the same 25 datasets and splits:

* `G_short`: `G` (64 candidates, leaf L2 100, 6 bits) on `F`'s short budget,
  so `G_short` against `F` is the candidates and against `G` the budget.
* `G_h4`: `G` at 4 rounds per batch instead of 8, the full budget.
* `L_short`: leaf L2 1 at 8 rounds per batch on the short budget, a cheap `L`.

    uv run python scripts/m3_runs/speed.py   # rewrites speed_*.txt
"""

from pathlib import Path

from configs import COMMON
from configs import JOBS as CONFIG_JOBS
from monster_benchmark import split_flags

SHORT = "--max-batches 2000 --patience-batches 250"
FULL = "--max-batches 5000 --patience-batches 1000"
GAIN = "--gain-candidates 64 --hessian-eps 100 --num-bits 6 --active-batches 128"

CONFIGS = {
    "G_short": f"{SHORT} --hashes-per-round 8 {GAIN}",
    "G_h4": f"{FULL} --hashes-per-round 4 {GAIN}",
    "L_short": f"{SHORT} --hashes-per-round 8 --active-batches 128 --hessian-eps 1",
}

JOBS = {job.replace("configs", "speed"): names for job, names in CONFIG_JOBS.items()}


def lines(name: str) -> list[str]:

    common = (
        f'python scripts/stream_full.py --path "$DATA" --dataset {name}'
        f"{split_flags(name)} --out results/speed {COMMON}"
    )

    return [f"{common} {flags} --label {label}" for label, flags in CONFIGS.items()]


def main() -> None:

    here = Path(__file__).parent

    for job, names in JOBS.items():
        header = [
            f"# Generated by speed.py: {', '.join(names)}.",
            "#",
            f"#     sbatch -c 8 --mem=96G --time=08:00:00 -J {job.replace('_', '-')} \\",
            f"#         scripts/m3_job.sh --stage {','.join(names)} \\",
            f"#         --serial scripts/m3_runs/{job}.txt",
            "",
        ]
        body = [line for name in names for line in lines(name)]
        (here / f"{job}.txt").write_text("\n".join(header + body) + "\n")
        print(f"{job}: {len(names)} datasets, {len(body)} runs")


if __name__ == "__main__":
    main()
