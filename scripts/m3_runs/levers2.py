"""Write the run lists for round 2 of the HashBoost lever screen on M3.

Round 1 (`levers.py`, README `m3`) found two levers. Gain-scored splits cut
small-pool error two- to tenfold, past XGBoost on UCIActivity, PAMAP2,
CrowdSourced and WISDM, but overfit Traffic (training error 0.003 against
0.067, validation 0.013 worse) and DREAMERA. Leaf L2 helps everywhere, most
at 100 on small pools and at 1 on Traffic and LenDB (0.0403, XGBoost 0.0471).

This round stacks them and tries to stop gain from overfitting large pools,
on the same base and datasets. `base` and `gain64` are rerun, which also
gives one rerun's spread for each:

* stacking: gain64 with L2 100, with 6 bits, or both; 256 candidates; gain16
  with L2 100
* regularised gain: a gain lambda of 100, with and without leaf L2 10; gain4
  with L2 1
* large-pool capacity: L2 100 alone, and L2 1 at 16 rounds per batch

Every pool gets every arm. Traffic and LenDB are too big for the feature cache
and are read and transformed each epoch.

    uv run python scripts/m3_runs/levers2.py   # rewrites levers2_*.txt
"""

from pathlib import Path

from levers import BASE
from monster_benchmark import split_flags

ARMS = {
    "base": "",
    "gain64": "--gain-candidates 64",
    "gain64_l2_100": "--gain-candidates 64 --hessian-eps 100",
    "gain64_bits6": "--gain-candidates 64 --num-bits 6",
    "gain64_l2_100_bits6": "--gain-candidates 64 --hessian-eps 100 --num-bits 6",
    "gain256": "--gain-candidates 256",
    "gain16_l2_100": "--gain-candidates 16 --hessian-eps 100",
    "gain16_glam100": "--gain-candidates 16 --gain-lambda 100",
    "gain16_glam100_l2_10": "--gain-candidates 16 --gain-lambda 100 --hessian-eps 10",
    "gain4_l2_1": "--gain-candidates 4 --hessian-eps 1",
    "l2_100": "--hessian-eps 100",
    "l2_1_h16": "--hessian-eps 1 --hashes-per-round 16 --active-batches 128",
}

JOBS = {
    "levers2_a": ["PAMAP2", "STEW", "InsectSound"],
    "levers2_b": ["CrowdSourced", "FordChallenge", "WISDM", "UCIActivity"],
    "levers2_c": ["DREAMERA", "Traffic"],
    "levers2_d": ["LenDB"],
}


def lines(name: str) -> list[str]:

    common = (
        f'python scripts/stream_full.py --path "$DATA" --dataset {name}'
        f"{split_flags(name)} --out results/levers2 {BASE}"
    )

    return [
        f"{common} {flags} --label {label}".replace("  ", " ")
        for label, flags in ARMS.items()
    ]


def main() -> None:

    here = Path(__file__).parent

    for job, names in JOBS.items():
        header = [
            f"# Generated by levers2.py: {', '.join(names)}.",
            "#",
            f"#     sbatch -c 8 --mem=96G --time=08:00:00 -J {job.replace('_', '-')} \\",
            f"#         scripts/m3_job.sh --stage {','.join(names)} \\",
            f"#         --serial scripts/m3_runs/{job}.txt",
            "",
        ]
        body = [line for name in names for line in lines(name)]
        (here / f"{job}.txt").write_text("\n".join(header + body) + "\n")
        print(f"{job}: {len(names)} datasets, {len(body)} runs")


if __name__ == "__main__":
    main()
