"""Write the run lists for the HashBoost lever screen on M3.

The whole-pool benchmark (README, `m3`) left HashBoost behind XGBoost on 17
of 25 MONSTER datasets, worst on small pools where it reaches zero training
error. This screens each lever from that discussion as one change from a fixed
base, with the base rerun in the same job:

* base: `fast` from the benchmark (8 bits, 8 rounds per batch, 128-batch
  window), same budget and tune stopping, plus the feature cache, which only
  saves time. The base also refits its readout (`round_class`), so the
  readout is paired against the very model it refits.
* `l2_*`: leaf L2 (`--hessian-eps`), XGBoost's reg_lambda.
* `sampled`: hard pairs drawn by cross entropy, not hardest first.
* `bits6`: 6-bit tables, 64 cells per round instead of 256.
* `lr05`: learning rate 0.05, XGBoost's.
* `win*`: frozen windows of 2 and 8 batches. 128 batches is tens to hundreds
  of epochs of a small pool, so the benchmark never really froze there.
* `gain*`: GainSplitter, the best of 4, 16 or 64 hard-pair splits per bit.
* `combo`: gain16 + l2_1 + sampled, a first guess at stacking them.

Seven small or mid pools get every arm; the readout needs the cache, so on
Traffic and LenDB (too big to cache) the base runs without it and only a subset
of arms runs. One run per arm, as everywhere in this screen.

    uv run python scripts/m3_runs/levers.py   # rewrites levers_*.txt
"""

from pathlib import Path

from monster_benchmark import split_flags

BASE = (
    "--model hashboost --compile --epochs 100000 --max-batches 5000 "
    "--eval-every 50 --patience-batches 1000 --hashes-per-round 8 "
    "--active-batches 128 --feature-cache-gb 20"
)

ARMS = {
    "base": "--readout round_class",
    "l2_1": "--hessian-eps 1",
    "l2_10": "--hessian-eps 10",
    "l2_100": "--hessian-eps 100",
    "sampled": "--sample-pairs",
    "bits6": "--num-bits 6",
    "lr05": "--lr 0.05",
    "win2": "--active-batches 2",
    "win8": "--active-batches 8",
    "gain4": "--gain-candidates 4",
    "gain16": "--gain-candidates 16",
    "gain64": "--gain-candidates 64",
    "combo": "--gain-candidates 16 --hessian-eps 1 --sample-pairs",
}

# the pools too big for the feature cache: no readout, fewer arms
LARGE = ["base", "l2_1", "l2_10", "sampled", "lr05", "gain4", "gain16", "combo"]

JOBS = {
    "levers_a": ["PAMAP2", "STEW", "InsectSound"],
    "levers_b": ["CrowdSourced", "FordChallenge", "WISDM", "UCIActivity"],
    "levers_c": ["DREAMERA", "Traffic"],
    "levers_d": ["LenDB"],
}

FULL = {"Traffic": False, "LenDB": False}


def lines(name: str) -> list[str]:

    common = (
        f'python scripts/stream_full.py --path "$DATA" --dataset {name}'
        f"{split_flags(name)} --out results/levers {BASE}"
    )
    arms = ARMS if FULL.get(name, True) else {a: ARMS[a] for a in LARGE}

    runs = []
    for label, flags in arms.items():
        if not FULL.get(name, True) and label == "base":
            flags = ""
        runs.append(f"{common} {flags} --label {label}".replace("  ", " "))

    return runs


def main() -> None:

    here = Path(__file__).parent

    for job, names in JOBS.items():
        header = [
            f"# Generated by levers.py: {', '.join(names)}.",
            "#",
            f"#     sbatch -c 8 --mem=96G --time=08:00:00 -J {job.replace('_', '-')} \\",
            f"#         scripts/m3_job.sh --stage {','.join(names)} \\",
            f"#         --serial scripts/m3_runs/{job}.txt",
            "",
        ]
        body = [line for name in names for line in lines(name)]
        (here / f"{job}.txt").write_text("\n".join(header + body) + "\n")
        print(f"{job}: {len(names)} datasets, {len(body)} runs")


if __name__ == "__main__":
    main()
